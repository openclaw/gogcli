package main

import (
	"bytes"
	"fmt"
	"os"
	"strconv"
	"strings"

	"github.com/openclaw/gogcli/internal/safetyprofile"
)

const usage = `Usage: bake-safety-profile <profile.yaml> <output.go>` + "\n"

func main() {
	args := os.Args[1:]
	if len(args) != 2 {
		_, _ = fmt.Fprint(os.Stderr, usage)
		os.Exit(2)
	}

	raw, err := os.ReadFile(args[0]) // #nosec G304 G703 -- build helper intentionally reads the requested profile path.
	if err != nil {
		_, _ = fmt.Fprintf(os.Stderr, "read profile: %v\n", err)
		os.Exit(1)
	}

	profile, err := safetyprofile.Parse(string(raw))
	if err != nil {
		_, _ = fmt.Fprintf(os.Stderr, "parse profile: %v\n", err)
		os.Exit(1)
	}

	out := generate(profile)
	if err := os.WriteFile(args[1], out, 0o600); err != nil { // #nosec G306 G703 -- build helper intentionally writes the requested generated Go path.
		_, _ = fmt.Fprintf(os.Stderr, "write output: %v\n", err)
		os.Exit(1)
	}
}

// generate emits a Go file that resolves the bakedSafety* package-level
// functions for safety_profile builds. Allow and deny rules are encoded as
// FNV-64a hashes in switch statements so that the rule set itself is no
// longer a contiguous, patchable string in the binary.
func generate(profile *safetyprofile.Profile) []byte {
	var out bytes.Buffer
	hasAllowRules := profile.AllowAll || len(profile.AllowRules) > 0

	out.WriteString("// Code generated by cmd/bake-safety-profile; DO NOT EDIT.\n")
	commentName := strings.ReplaceAll(strings.ReplaceAll(profile.Name, "\n", " "), "\r", " ")
	fmt.Fprintf(&out, "// Profile: %s (%d allow, %d deny, allow-all=%t)\n", commentName, len(profile.AllowRules), len(profile.DenyRules), profile.AllowAll)
	out.WriteString("// Hash: FNV-64a over dotted command paths.\n")
	out.WriteString("//go:build safety_profile\n\n")
	out.WriteString("package cmd\n\n")

	out.WriteString("const bakedSafetyProfileNameConst = ")
	out.WriteString(strconv.Quote(profile.Name))
	out.WriteString("\n\n")

	out.WriteString("func bakedSafetyEnabled() bool       { return true }\n")
	out.WriteString("func bakedSafetyProfileName() string { return bakedSafetyProfileNameConst }\n")
	fmt.Fprintf(&out, "func bakedSafetyHasAllowRules() bool { return %t }\n\n", hasAllowRules)

	writeMatcher(&out, "bakedSafetyAllowMatch", profile.AllowRules, profile.AllowAll, false)
	out.WriteString("\n")
	writeMatcher(&out, "bakedSafetyDenyMatch", profile.DenyRules, false, false)
	out.WriteString("\n")
	writeMatcher(&out, "bakedSafetyAllowExactMatch", profile.AllowRules, profile.AllowAll && len(profile.DenyRules) == 0, true)
	out.WriteString("\n")
	writeLockedFlags(&out, profile.LockedFlags)
	out.WriteString("\n")
	writeDeniedValues(&out, profile.DeniedValues)

	return out.Bytes()
}

// writeDeniedValues emits the denied value lookups. The command path and flag name are
// hashed together like a command rule, and the rule case says whether it refuses any
// value. Each refused value is hashed with its path and flag (DeniedValueKey), and the
// runtime hashes the value it was given the same way, so no denied value is a string an
// in-place edit of the binary could change. The count travels alongside so the runtime
// can tell that every rule matched a real flag without the names being written down.
func writeDeniedValues(out *bytes.Buffer, rules []safetyprofile.DeniedValue) {
	out.WriteString("func bakedSafetyDeniedValueRule(path []string, flag string) (bool, bool) {\n")
	if len(rules) == 0 {
		out.WriteString("\treturn false, false\n}\n")
		out.WriteString("\nfunc bakedSafetyDeniedValueMatch(path []string, flag, value string) bool {\n\treturn false\n}\n")
		out.WriteString("\nfunc bakedSafetyDeniedValueRuleCount() int { return 0 }\n")
		return
	}
	out.WriteString("\tswitch bakedSafetyHashPath(append(append([]string(nil), path...), flag)) {\n")
	seen := make(map[uint64]string, len(rules))
	var valueCases []string
	for _, rule := range rules {
		key := rule.Path + "." + rule.Flag
		h := safetyprofile.HashRule(key)
		if existing, dup := seen[h]; dup {
			fmt.Fprintf(os.Stderr, "bake-safety-profile: hash collision between denied value rules %q and %q (FNV-64a=%#x)\n", existing, key, h)
			os.Exit(1)
		}
		seen[h] = key
		anyValue := len(rule.Values) == 1 && rule.Values[0] == "*"
		fmt.Fprintf(out, "\tcase 0x%016x:\n\t\treturn true, %t\n", h, anyValue)
		if anyValue {
			continue
		}
		for _, value := range rule.Values {
			valueKey := safetyprofile.DeniedValueKey(rule.Path, rule.Flag, value)
			vh := safetyprofile.HashRule(valueKey)
			if existing, dup := seen[vh]; dup {
				fmt.Fprintf(os.Stderr, "bake-safety-profile: hash collision between denied value rules %q and %q (FNV-64a=%#x)\n", existing, valueKey, vh)
				os.Exit(1)
			}
			seen[vh] = valueKey
			valueCases = append(valueCases, fmt.Sprintf("0x%016x", vh))
		}
	}
	out.WriteString("\t}\n\treturn false, false\n}\n")

	out.WriteString("\nfunc bakedSafetyDeniedValueMatch(path []string, flag, value string) bool {\n")
	if len(valueCases) == 0 {
		out.WriteString("\treturn false\n}\n")
	} else {
		out.WriteString("\tswitch bakedSafetyDeniedValueHash(path, flag, value) {\n")
		for _, c := range valueCases {
			fmt.Fprintf(out, "\tcase %s:\n\t\treturn true\n", c)
		}
		out.WriteString("\t}\n\treturn false\n}\n")
	}
	fmt.Fprintf(out, "\nfunc bakedSafetyDeniedValueRuleCount() int { return %d }\n", len(rules))
}

// writeLockedFlags emits the locked flag lookup. Names are hashed like the command
// rules; the locked boolean values are literals because the flag parser consumes them. The
// count travels alongside so the runtime can tell that every lock matched a real
// flag without the names being written down.
func writeLockedFlags(out *bytes.Buffer, flags []safetyprofile.LockedFlag) {
	out.WriteString("func bakedSafetyLockedFlag(name string) (string, bool) {\n")
	if len(flags) == 0 {
		out.WriteString("\treturn \"\", false\n}\n")
		out.WriteString("\nfunc bakedSafetyLockedFlagCount() int { return 0 }\n")
		return
	}
	out.WriteString("\tswitch bakedSafetyHashPath([]string{name}) {\n")
	seen := make(map[uint64]string, len(flags))
	for _, flag := range flags {
		h := safetyprofile.HashRule(flag.Name)
		if existing, dup := seen[h]; dup {
			fmt.Fprintf(os.Stderr, "bake-safety-profile: hash collision between locked flags %q and %q (FNV-64a=%#x)\n", existing, flag.Name, h)
			os.Exit(1)
		}
		seen[h] = flag.Name
		fmt.Fprintf(out, "\tcase 0x%016x:\n\t\treturn %s, true\n", h, strconv.Quote(flag.Value))
	}
	out.WriteString("\t}\n\treturn \"\", false\n}\n")
	fmt.Fprintf(out, "\nfunc bakedSafetyLockedFlagCount() int { return %d }\n", len(flags))
}

func writeMatcher(out *bytes.Buffer, name string, rules []string, matchAll, exact bool) {
	fmt.Fprintf(out, "func %s(path []string) bool {\n", name)
	if matchAll {
		out.WriteString("\treturn true\n}\n")
		return
	}
	if len(rules) == 0 {
		out.WriteString("\treturn false\n}\n")
		return
	}

	out.WriteString("\tif len(path) == 0 {\n\t\treturn false\n\t}\n")
	if exact {
		out.WriteString("\tswitch bakedSafetyHashPath(path) {\n")
	} else {
		out.WriteString("\tfor i := 1; i <= len(path); i++ {\n")
		out.WriteString("\t\tswitch bakedSafetyHashPath(path[:i]) {\n")
	}
	out.WriteString("\t\tcase ")

	cases := make([]string, 0, len(rules))
	seen := make(map[uint64]string, len(rules))
	for _, rule := range rules {
		h := safetyprofile.HashRule(rule)
		if existing, dup := seen[h]; dup {
			fmt.Fprintf(os.Stderr, "bake-safety-profile: hash collision between %q and %q (FNV-64a=%#x); pick a different name or extend the hash\n", existing, rule, h)
			os.Exit(1)
		}
		seen[h] = rule
		cases = append(cases, fmt.Sprintf("0x%016x", h))
	}

	const perLine = 4
	for i, c := range cases {
		out.WriteString(c)
		if i == len(cases)-1 {
			break
		}
		out.WriteString(",")
		if (i+1)%perLine == 0 {
			out.WriteString("\n\t\t\t")
		} else {
			out.WriteString(" ")
		}
	}
	out.WriteString(":\n\t\t\treturn true\n")
	out.WriteString("\t}\n")
	if !exact {
		out.WriteString("\t}\n")
	}
	out.WriteString("\treturn false\n}\n")
}
